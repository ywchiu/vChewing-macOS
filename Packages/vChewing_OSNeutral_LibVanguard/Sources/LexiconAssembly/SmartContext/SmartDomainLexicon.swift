  ///
  /// 目前是內建的靜態表。日後若要讓使用者擴充，擴充項應併入本表的查詢結果，
  /// 而不是另立一套加權管道——多一條管道就多一組要調的權重。
  public enum SmartDomainLexicon {
    // MARK: Public

    /// 查一個詞屬於哪些領域。不屬於任何領域時回傳空集合。
    ///
    /// - Complexity: O(1)。
    public static func domains(of term: String) -> Set<SmartDomain> {
      index[term] ?? []
    }

    /// 取某領域的全部詞彙。
    public static func terms(of domain: SmartDomain) -> Set<String> {
      byDomain[domain] ?? []
    }

    /// 本表是否收錄該詞。
    public static func contains(_ term: String) -> Bool {
      index[term] != nil
    }

    /// 前景 app 的粗類別所隱含的領域。
    ///
    /// 這是「語境」的一部分，不是「學習」——在編輯器裡打字，技術詞彙本來就比較可能，
    /// 這件事不需要學。真正需要學的「這個使用者在這類 app 裡偏好哪些詞」是另一回事，
    /// 由 Phase 4 的 `SmartPreferenceStore` 負責，與本表無關。
    ///
    /// `chat` 與 `browser` 刻意**不**對應任何領域：聊天與瀏覽的內容跨度太大，
    /// 硬給一個領域只會製造假訊號。
    public static func impliedDomain(of appCategory: SmartAppCategory) -> SmartDomain? {
      switch appCategory {
      case .editor, .terminal: .tech
      case .mail: .business
      case .chat, .browser, .other: nil
      }
    }

