// MARK: - LXAssembly.SmartDomain

extension LXAssembly {
  /// 語境領域。
  ///
  /// ## 為什麼需要這個東西（請先讀完再改動本檔）
  ///
  /// 唯音的原廠辭典是**純單元圖**的：244,162 筆全部只有「讀音 → 詞 → 權重」，
  /// 沒有任何 `previous` 欄位。Homa 的雙元／三元圖機制存在，但它唯一的餵食來源是
  /// POM——也就是**使用者自己教過的東西**（見 `LXFacade.unigramsFor` 的 POM 注入段）。
  /// 隨附的 `template-associatedPhrases` 也幫不上忙：它的 head 全是單字，而且語義是
  /// 「詞的補完」（`行`＋`程`＝行程），不是「這個詞後面接什麼」。
  ///
  /// 結論是：**冷啟動時（使用者還沒教過任何東西），本輸入法沒有任何共現統計可用。**
  /// 一個不含模型、不含語料的 scorer 要在這種條件下做上下文消歧，唯一的辦法就是
  /// 一份人工的領域詞表——也就是本檔。
  ///
  /// ## 本表的紀律
  ///
  /// 1. **依領域歸屬收詞，不依測試答案收詞。** 本表若照著 benchmark 的期望值來寫，
  ///    benchmark 就只是在量「我有沒有把答案抄進來」，那個數字沒有意義。收詞的判準
  ///    一律是「這個詞在一般台灣中文裡是否屬於該領域」，與任何測試案例無關。
  /// 2. **只收雙字以上的詞。** 單字詞若被加權，會擾動 DP 在「單字 vs 多字詞」之間
  ///    的結構性平衡（那個差距動輒 5 以上），代價遠大於收益。
  /// 3. **一個詞可以屬於多個領域**，此時它的投票會被稀釋（見 `domains(of:)` 的用法）。
  /// 4. **詞表同時是「觸發詞」與「被加權詞」。** 語境裡出現某領域的詞，就為該領域投票；
  ///    候選詞屬於得票領域，就得到加權。不另設一份觸發詞表——維護兩份必然會走樣。
  ///
  /// ## 這份表做得到什麼、做不到什麼
  ///
  /// 做得到：「詞本身有領域屬性」的消歧。`執行` 與 `程式` 同屬技術領域，故技術語境下
  /// `程式` 能贏過 `城市`。
  ///
  /// **做不到**：純語意搭配。`橫渡` 與 `紅海`、`充滿` 與 `詩意` 之間的關係是語意的，
  /// 不是領域的——沒有語料或模型就是做不到。那正是 POM（使用者自己的記憶）與
  /// 「學習階段」存在的理由，不該由本表硬撐。
  public enum SmartDomain: String, Codable, Sendable, CaseIterable {
    /// 程式設計與資訊技術。
    case tech
    /// 商務書信與辦公。
    case business
    /// 飲食。
    case food
    /// 旅遊與地理。
    case travel
    /// 金融與財經。
    case finance
    /// 文藝與情感。
    case literature
    /// 醫療與健康。
    case health
  }
}

